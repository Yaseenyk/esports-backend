// Regenerates migrations/0051_v3_core.sql from src/v3/db/schema.ts (drizzle-kit), then makes it idempotent and appends the hand-written triggers.
// Usage: rm -rf src/v3/db/kit && npx drizzle-kit generate --name v3_core && node scripts/v3-migration.mjs
import { readFileSync, writeFileSync } from "node:fs";
let sql = readFileSync(new URL("../src/v3/db/kit/0000_v3_core.sql", import.meta.url), "utf8");
sql = sql
  .replace(/--> statement-breakpoint\n?/g, "\n")
  .replace(/CREATE TABLE `/g, "CREATE TABLE IF NOT EXISTS `")
  .replace(/CREATE UNIQUE INDEX `/g, "CREATE UNIQUE INDEX IF NOT EXISTS `")
  .replace(/CREATE INDEX `/g, "CREATE INDEX IF NOT EXISTS `");
const header = `-- Esports Hub v3 core (ADR-1 option A: everything on D1). GENERATED by drizzle-kit from src/v3/db/schema.ts (scripts/v3-migration.mjs), then made
-- idempotent. Additive only: 14 new tables, no legacy table is changed here (the three users columns are in 0052). Every v3 route is behind a flag that is
-- OFF by default and answers 404 before touching these tables, so a Worker can be deployed before this file is applied.
-- Rollback is "empty, do not drop".
`;
const triggers = `
-- Append-only dispute history. Exactly two changes are allowed, both for account deletion: actor_user_id to NULL, and note to '[deleted]'.
CREATE TRIGGER IF NOT EXISTS trg_dispute_events_append_only BEFORE UPDATE ON dispute_events
WHEN NEW.id IS NOT OLD.id OR NEW.dispute_id IS NOT OLD.dispute_id OR NEW.actor_role IS NOT OLD.actor_role OR NEW.action IS NOT OLD.action
  OR NEW.from_status IS NOT OLD.from_status OR NEW.to_status IS NOT OLD.to_status OR NEW.created_at IS NOT OLD.created_at
  OR (NEW.note IS NOT OLD.note AND NEW.note IS NOT '[deleted]')
BEGIN SELECT RAISE(ABORT, 'dispute_events is append-only'); END;
`;
writeFileSync(new URL("../migrations/0051_v3_core.sql", import.meta.url), header + sql.trim() + "\n" + triggers);
console.log("wrote migrations/0051_v3_core.sql");
